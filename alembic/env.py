"""Alembic environment using only an explicit validated database URL."""

from __future__ import with_statement

import os
import re

from alembic import context
from sqlalchemy import engine_from_config, pool, text

from backend.config import ConfigurationError, load_settings
from backend.models import Base


config = context.config
target_metadata = Base.metadata
_SCHEMA_PATTERN = re.compile(r"^aegisqa_it_[a-f0-9]{32}$")


def _database_url() -> str:
    try:
        settings = load_settings()
    except ConfigurationError as error:
        raise RuntimeError("Database migration configuration is invalid.") from error
    if settings.database_url is None:
        raise RuntimeError("AEGISQA_DATABASE_URL is required for migrations.")
    return settings.database_url


def _migration_schema():
    """Accept only the per-run schema generated by the integration harness."""

    schema = os.environ.get("AEGISQA_ALEMBIC_SCHEMA")
    if schema is None:
        return None
    if not _SCHEMA_PATTERN.fullmatch(schema):
        raise RuntimeError("Alembic schema configuration is invalid.")
    return schema


def _set_committed_search_path(connection, schema) -> None:
    """Set the test schema outside Alembic's migration transaction."""

    if schema is None:
        return
    connection.execute(text('SET search_path TO "{0}"'.format(schema)))
    # SQLAlchemy 2.x starts a transaction for SET. Commit it before Alembic
    # establishes the transaction that owns migration changes.
    connection.commit()


def run_migrations_offline() -> None:
    schema = _migration_schema()
    context.configure(
        url=_database_url(),
        target_metadata=target_metadata,
        literal_binds=True,
        version_table_schema=schema,
    )
    with context.begin_transaction():
        context.run_migrations()


def run_migrations_online() -> None:
    schema = _migration_schema()
    configuration = config.get_section(config.config_ini_section)
    configuration["sqlalchemy.url"] = _database_url()
    connectable = engine_from_config(configuration, prefix="sqlalchemy.", poolclass=pool.NullPool)
    with connectable.connect() as connection:
        _set_committed_search_path(connection, schema)
        context.configure(
            connection=connection,
            target_metadata=target_metadata,
            version_table_schema=schema,
        )
        with context.begin_transaction():
            context.run_migrations()


if context.is_offline_mode():
    run_migrations_offline()
else:
    run_migrations_online()
